export type Key = keyof typeof M;
export type Vars = Record<string, string | number>;

export function t(key: Key, vars?: Vars): string {
  const pair = M[key];
  let text: string = prefs.lang === "id" ? pair[0] : pair[1];
  if (text.includes("|")) {
    const [one, other] = text.split("|");
    text = vars?.n === 1 ? one : other;
  }
  return vars ? text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? "")) : text;
}

/** Interface-language text from bilingual data. */
export function l(value: L10n | string | undefined): string {
  if (!value) return "";
  return typeof value === "string" ? value : value[prefs.lang];
}

export const locale = () => (prefs.lang === "id" ? "id-ID" : "en-US");

export function fmtDate(iso: string, opts: Intl.DateTimeFormatOptions = { day: "numeric", month: "short", year: "numeric" }) {
  return new Intl.DateTimeFormat(locale(), opts).format(new Date(`${iso}T00:00:00`));
}

/** Seconds as h:mm:ss timeline text (00:14:32). */
export function fmtClock(seconds: number) {
  const s = Math.max(0, Math.floor(seconds));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const sec = s % 60;
  return [h, m, sec].map((v) => String(v).padStart(2, "0")).join(":");
}

export function fmtDuration(seconds: number) {
  const m = Math.round(seconds / 60);
  if (m < 60) return prefs.lang === "id" ? `${m} mnt` : `${m} min`;
  const h = Math.floor(m / 60);
  const rest = m % 60;
  return prefs.lang === "id" ? `${h} j ${rest} mnt` : `${h} h ${rest} min`;
}
