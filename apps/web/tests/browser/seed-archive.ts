import { createHash } from "node:crypto";
import { pack } from "../../src/lib/server/archive";

/**
 * A tiny synthetic case archive for browser tests, packed with the app's own `pack()`.
 * Every finding quotes its source passage exactly, so import validation accepts it,
 * and the four findings cover each finding status.
 */
export const SEED = {
  caseTitle: "Acceptance synthetic case",
  hearingTitle: "Synthetic warehouse examination",
  segments: 8,
  findings: 4,
} as const;

const created = "2026-01-05T09:00:00.000Z";
const caseId = "seed-case";
const documents = [
  {
    id: "seed-doc-report",
    name: "synthetic-witness-report.txt",
    text: "Synthetic witness report. The supervisor signed the jade receipt at the front desk. The witness reached the warehouse before the inspector.",
  },
  {
    id: "seed-doc-log",
    name: "synthetic-inspection-log.txt",
    text: "Synthetic inspection log. The inspector arrived at ten. The loading door was open from noon. The jade receipt was filed at the warehouse.",
  },
];
const turns: [string, string][] = [
  ["Counsel", "Please tell the court when you reached the warehouse."],
  ["Witness", "I reached the warehouse at 9:30 that morning."],
  ["Counsel", "Who signed the jade receipt?"],
  ["Witness", "The supervisor signed the jade receipt at the front desk."],
  ["Counsel", "Was the loading door open?"],
  ["Witness", "The loading door was locked all day."],
  ["Counsel", "Did anyone else enter?"],
  ["Witness", "A courier may have entered after lunch."],
];

export function seedArchive() {
  const files: Record<string, Uint8Array> = {};
  const docs = documents.map((doc) => {
    const data = new TextEncoder().encode(doc.text),
      file = `originals/${doc.id}`;
    files[file] = data;
    return {
      id: doc.id,
      case_id: caseId,
      name: doc.name,
      mime: "text/plain",
      pages: 1,
      created_at: created,
      file,
      sha256: createHash("sha256").update(data).digest("hex"),
    };
  });
  const sources = documents.map((doc) => ({
    id: `${doc.id}-p1`,
    document_id: doc.id,
    document_name: doc.name,
    page: 1,
    section: "",
    text: doc.text,
    score: 0,
  }));
  const segments = turns.map(([speaker, text], index) => ({
    id: `seed-seg-${index + 1}`,
    hearing_id: "seed-hearing",
    speaker,
    text,
    start: index * 10,
    end: index * 10 + 8,
    confidence: null,
    origin: "imported",
    analysis_state: "complete",
    analysis_error: null,
    created_at: `2026-01-05T09:00:0${index}.000Z`,
  }));
  const finding = (
    segment: number,
    status: string,
    title: string,
    explanation: string,
    citations: { chunk_id: string; quote: string; relation: string }[],
  ) => ({
    id: `seed-finding-${segment}`,
    segment_id: `seed-seg-${segment}`,
    status,
    title,
    explanation,
    uncertainty: "Synthetic example for testing.",
    verification: "Compare the statement with the cited passage.",
    question: `What does the record show about statement ${segment}?`,
    citations,
    review: {},
    legal: [],
    mode: "imported",
    elapsed_ms: 0,
    reviewed: false,
    note: "",
    created_at: `2026-01-05T09:01:0${segment}.000Z`,
  });
  const manifest = {
    format: "jude",
    version: 1,
    kind: "case",
    case: {
      id: caseId,
      title: SEED.caseTitle,
      reference: "SYNTHETIC-TEST",
      description: "Synthetic material generated by the browser tests.",
      synthetic: true,
      status: "ready",
      created_at: created,
      speakers: {},
    },
    documents: docs,
    sources,
    hearings: [
      {
        id: "seed-hearing",
        case_id: caseId,
        title: SEED.hearingTitle,
        date: "2026-01-05",
        kind: "imported",
        status: "complete",
        source_document_id: null,
        created_at: created,
      },
    ],
    segments,
    findings: [
      finding(
        2,
        "context_needed",
        "The accounts differ on arrival time",
        "The accounts describe different arrival times.",
        [
          {
            chunk_id: "seed-doc-log-p1",
            quote: "The inspector arrived at ten.",
            relation: "context",
          },
        ],
      ),
      finding(
        4,
        "supported",
        "Both accounts name the supervisor",
        "The report names the same signer as the testimony.",
        [
          {
            chunk_id: "seed-doc-report-p1",
            quote: "The supervisor signed the jade receipt at the front desk.",
            relation: "supports",
          },
        ],
      ),
      finding(
        6,
        "potential_inconsistency",
        "Door status conflicts with the log",
        "The log records the loading door open from noon.",
        [
          {
            chunk_id: "seed-doc-log-p1",
            quote: "The loading door was open from noon.",
            relation: "conflicts",
          },
        ],
      ),
      finding(
        8,
        "insufficient_evidence",
        "No record of a courier",
        "No supplied document mentions a courier.",
        [],
      ),
    ],
    links: [],
  };
  return Buffer.from(pack(manifest, files));
}
